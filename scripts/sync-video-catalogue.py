"""Derive video picker metadata from the existing generated canonical catalogue."""
import runpy
from pathlib import Path

root = Path(__file__).resolve().parent.parent
rows = runpy.run_path(str(root / "alibaba-token-plan/fallback_models.py"))["MEDIA_MODELS"]
output = '# Generated by scripts/sync-video-catalogue.py; do not hand-edit.\nVIDEO_MODELS = (\n'
for model, kind, tiers, regions in rows:
    if kind != "video":
        continue
    modes = ["image"] if model.endswith(("-i2v", "-r2v")) else ["text"]
    output += f'    {dict(id=model, display=model, modalities=modes, tiers=tiers, regions=regions)!r},\n'
output += ')\n'
(root / "video-gen/alibaba-token-plan-video/catalogue.py").write_text(output)
