"""Derive video picker metadata from the existing generated canonical catalogue."""
import runpy
import shutil
from pathlib import Path

root = Path(__file__).resolve().parent.parent
canonical = root / "alibaba-token-plan/fallback_models.py"
shutil.copyfile(canonical, root / "alibaba-token-plan-media/fallback_models.py")
rows = runpy.run_path(str(canonical))["MEDIA_MODELS"]
output = '# Generated by scripts/sync-video-catalogue.py; do not hand-edit.\nVIDEO_MODELS = (\n'
for model, kind, tiers, regions in rows:
    if kind != "video":
        continue
    modes = ["image"] if model.endswith(("-i2v", "-r2v")) else ["text"]
    # These describe our implemented subset, not vendor maximums or inference health.
    subsets = {
        "happyhorse-1.1-t2v": (["720p"], "Text prompt; 5s, 720p, 16:9; live validation pending"),
        "happyhorse-1.1-i2v": (["720p"], "Requires image_url; 5s, 720p, source ratio; live validation pending"),
        "happyhorse-1.1-r2v": (["720p"], "Requires 1–9 reference_image_urls, not image_url; 5s, 720p, 16:9; live validation pending"),
        "wan3.0-video": (["480p", "720p"], "Text prompt only; 5s, 480p/720p, adaptive ratio; live validation pending"),
    }
    resolution, strengths = subsets[model]  # New IDs require an explicit contract review.
    output += f'    {dict(id=model, display=model, modalities=modes, tiers=tiers, regions=regions, resolutions=resolution, min_duration=5, max_duration=5, strengths=strengths)!r},\n'
output += ')\n'
(root / "alibaba-token-plan-media/video/catalogue.py").write_text(output)
